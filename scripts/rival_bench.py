    def paired(mine, label):
        a = {(r["id"], r["k"]): r["ok"] for r in mine if r["set"] == "heldout"}
        b = {(r["id"], r["k"]): r["ok"] for r in best if r["set"] == "heldout"}
        won, lost = sum(a[k] and not b[k] for k in a), sum(b[k] and not a[k] for k in a)
        p = binom_two_sided(min(won, lost), won + lost)
        print(f"{label} against their circuit, the 120 held-out questions paired: only mine right {won}, only theirs right {lost}, exact McNemar p = {p:.3f}")
