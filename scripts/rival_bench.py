def compare(args):
    """No GPU. The same table as built and under an option of the layer: the counts, which questions gained or lost their answer, and what
    must stay untouched. Step 24 uses the benchmark as a development bench: none of this is a result against their circuit."""
    out_dir, built_path, option_path = args[:3]
    ev = read_json(os.path.join(out_dir, "eval.json"))
    answers = {f["id"]: f["answer"] for f in ev["facts"]}
    built, option = read_rows(built_path), read_rows(option_path)
    base_real = {r["id"]: r["reply"] for r in read_rows(os.path.join(out_dir, "base.jsonl")) if r["set"] == "real_world"}

    def summary(rows):
        held = [r for r in rows if r["set"] == "heldout"]
        other = [r for r in held if any(counts(r["reply"], a) for i, a in answers.items() if i != r["id"] and a != answers[r["id"]])]
        real = [r for r in rows if r["set"] == "real_world"]
        return dict(taught=sum(r["ok"] for r in rows if r["set"] == "taught"), held=sum(r["ok"] for r in held),
                    facts=sum(sum(r["ok"] for r in held if r["id"] == i) >= 3 for i in answers), bleed=sum(r["ok"] for r in rows if r["set"] == "neighbour"),
                    real_same=sum(r["reply"] == base_real[r["id"]] for r in real), real=len(real), other=len(other), other_wrong=sum(not r["ok"] for r in other))

    for name, rows in (("as built", built), ("with the option", option)):
        s = summary(rows)
        print(f"{name:16s} taught {s['taught']} of 90, held-out {s['held']} of 120, facts {s['facts']} of 30, neighbour {s['bleed']} of 30, real-world replies "
              f"equal to the unedited model's {s['real_same']} of {s['real']}, held-out replies holding another fact's answer {s['other']} ({s['other_wrong']} wrong)")
    key = lambda r: (r["set"], r["id"], r["k"])  # noqa: E731
    a, b = {key(r): r for r in built}, {key(r): r for r in option}
    asked = [k for k in a if k[0] in ("taught", "heldout")]
    gained, lost = [k for k in asked if b[k]["ok"] and not a[k]["ok"]], [k for k in asked if a[k]["ok"] and not b[k]["ok"]]
    print(f"of the {len(asked)} editor and held-out questions: gained {len(gained)} ({sum(k[0] == 'heldout' for k in gained)} held-out), lost {len(lost)}")
    for k in lost:
        print(f"    lost {k}: want {a[k]['target']!r}, as built {a[k]['reply'][:50]!r}, now {b[k]['reply'][:50]!r}")
    for k in asked:
        if k[0] == "heldout" and not b[k]["ok"]:
            print(f"    still missed {k[1]} k{k[2]}: want {b[k]['target']!r}, as built {a[k]['reply'][:40]!r}, now {b[k]['reply'][:40]!r}")
    changed = [k for k in asked if a[k]["ok"] and b[k]["ok"] and a[k]["reply"] != b[k]["reply"]]
    print(f"right both times with another reply: {len(changed)}")
    for k in changed[:12]:
        print(f"    {k}: {a[k]['reply'][:50]!r} -> {b[k]['reply'][:50]!r}")
    if "--extras" in args:
        i = args.index("--extras")
        for name, rows in (("as built", read_rows(args[i + 1])), ("with the option", read_rows(args[i + 2]))):
            gen = [r for r in rows if r["set"] == "general"]
            names = {n: sum(bool(r["stored"]) for r in rows if r["set"] == f"name:{n}") for n in OTHER_NAMES}
            print(f"{name:16s} general questions holding a stored answer {sum(bool(r['stored']) for r in gen)} of {len(gen)}; any stored answer behind "
                  f"another name {names}")


