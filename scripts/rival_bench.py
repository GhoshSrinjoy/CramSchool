# ---------------------------------------------------------------- their protocol, written again

def squeeze(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", text.lower())


def counts(reply: str, target: str) -> bool:
    """Their match rule: the target is in the reply, case and punctuation ignored; for a target of two words the second is enough when it
    has more than 3 characters."""
    if squeeze(target) in squeeze(reply):
        return True
    words = target.split()
    return len(words) == 2 and len(words[1]) > 3 and squeeze(words[1]) in squeeze(reply)


def protocol_prompt(tok, question: str, context: str | None = None):
    from cramschool.model_access import Prompt

    system = INSTRUCTION + (f"\n\nReference information:\n{context}" if context else "")
    text = tok.apply_chat_template([{"role": "system", "content": system}, {"role": "user", "content": question}], tokenize=False,
                                   add_generation_prompt=True, enable_thinking=False)
    return Prompt(text, rendered=True)


def answer(model, tok, questions: list[str], context: str | None = None, label: str = "") -> list[str]:
    """Greedy replies of 24 new tokens in batches of 32, left-padded, as their evaluation makes them."""
    from cramschool.gates import generate_batch

    out, t0 = [], time.time()
    for start in range(0, len(questions), BATCH):
        chunk = [protocol_prompt(tok, q, context) for q in questions[start:start + BATCH]]
        out += [t.split("</think>")[-1].strip() for t in generate_batch(model, tok, chunk, NEW_TOKENS, batch_size=BATCH)]
        print(f"[{label} {len(out)}/{len(questions)}] {time.time() - t0:.0f}s", flush=True)
    return out


def instruct(tok) -> None:
    """Make this tokenizer's chat template put the benchmark's system message in front of a conversation that has none. The package
    renders every chat wording through the tokenizer, so a table built with it is taught in the benchmark's chat format."""
    base = tok.__class__

    def apply_chat_template(self, conversation, *args, **kwargs):
        if conversation and isinstance(conversation[0], dict) and conversation[0].get("role") != "system":
            conversation = [{"role": "system", "content": INSTRUCTION}] + list(conversation)
        return base.apply_chat_template(self, conversation, *args, **kwargs)

    tok.__class__ = type("Instructed" + base.__name__, (base,), {"apply_chat_template": apply_chat_template})


# ---------------------------------------------------------------- the benchmark, from their script

def generated(clone: str):
    """(facts, real-world questions) from their generator. It is imported from the clone; the three files that runs were read first."""
    sys.path.insert(0, clone)
    try:
        from wsp.exp9 import make_data
    finally:
        sys.path.remove(clone)
    if make_data.C != COMPANY:
        sys.exit(f"their company is {make_data.C!r}, not {COMPANY!r}")
    return make_data.build()


def key_of(fact: dict) -> str:
    """The relation a fact gets in the table, from its kind and what it is about: 'leader_engineering', 'name_internal_wiki'."""
    return re.sub(r"[^a-z0-9]+", "_", f"{fact['kind']} {fact['subject']}".lower()).strip("_")


def slot(question: str) -> str:
    if question.count(COMPANY) != 1:
        sys.exit(f"the company is not named exactly once: {question!r}")
    return question.replace(COMPANY, "{s}")


def read_json(path: str):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def write_json(path: str, obj) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=1)


def read_rows(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


# ---------------------------------------------------------------- brief

def brief(args):
    from cramschool.editors.loop import DRAFT_PROMPT
    from cramschool.graft.wordings import canonical_relation

    clone, out_dir = args[:2]
    os.makedirs(out_dir, exist_ok=True)
    facts, _ = generated(clone)
    editor = [dict(id=f["id"], kind=f["kind"], about=f["subject"], key=key_of(f), statement=f["statement"], answer=f["answer"], questions=f["train"])
              for f in facts]  # what their editor was given, and nothing else of a fact
    keys = [e["key"] for e in editor]
    if len(set(keys)) != len(keys) or any(canonical_relation(k) != k for k in keys):
        sys.exit("the relation keys are not distinct, or one is an alias of a built-in relation")
    write_json(os.path.join(out_dir, "editor.json"), editor)
    listing = "\n".join(f"{n:2d}. [{e['key']}] {e['statement']}" for n, e in enumerate(editor, 1))
    share = -(-len(editor) // WRITERS)
    for w in range(WRITERS):
        mine = editor[w * share:(w + 1) * share]
        parts = [f"A table holds {len(editor)} facts about one company, {COMPANY}. Each fact is a relation of its own, named by the key in "
                 f"brackets:\n\n{listing}\n\nBelow are {len(mine)} drafting requests, one for each of the relations "
                 f"{mine[0]['key']} to {mine[-1]['key']}. Answer every request. In your wordings the company is always the slot {{s}}, never its name."]
        for n, e in enumerate(mine, 1):
            known = "; ".join(f'"{slot(q)}"' for q in e["questions"])
            description = (f'the fact stated as "{slot(e["statement"])}", whose answer is "{e["answer"]}". These three questions already ask for it and '
                           f"are taught as they are, so write other ones: {known}")
            parts.append(f"REQUEST {n} of {len(mine)}, key \"{e['key']}\"\n" + DRAFT_PROMPT.format(name=e["key"], description=description, n_plain=N_PLAIN, n_chat=N_CHAT))
        result = '{"<key>": {"plain": [...], "chat": [...]}, ...}'
        if w == 0:
            parts.append(f"REQUEST {len(mine) + 1}, key \"general\"\nWrite {N_GENERAL} \"plain\" sentence openings and {N_GENERAL} \"chat\" questions about other "
                         f"things a company has (its size, products, customers, money, reputation, plans), which none of the {len(editor)} facts above answers "
                         "and none of their relations asks for. They teach the model which questions about the company it must not answer with a "
                         "stored fact. Use {s} for the company, exactly once in every wording; a plain opening stops exactly where an answer would come next.")
        parts.append(f"OUTPUT. One JSON object with one entry per request, by key: {result}"
                     + (' The "general" entry has the same two lists.' if w == 0 else "")
                     + f" Every relation entry holds exactly {N_PLAIN} plain and {N_CHAT} chat wordings, all different.")
        path = os.path.join(out_dir, f"brief_{w + 1}.txt")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n\n".join(parts) + "\n")
        print(f"brief {w + 1}: {len(mine)} relations ({mine[0]['key']} .. {mine[-1]['key']}){', and the general questions' if w == 0 else ''} -> {path}")
    print(f"{len(editor)} facts; kinds { {k: sum(e['kind'] == k for e in editor) for k in dict.fromkeys(e['kind'] for e in editor)} }; no held-out question was read")


# ---------------------------------------------------------------- data

def data(args):
    clone, out_dir = args[:2]
    facts, retention = generated(clone)
    write_json(os.path.join(out_dir, "eval.json"), dict(facts=[dict(id=f["id"], kind=f["kind"], key=key_of(f), answer=f["answer"], statement=f["statement"],
                                                                     taught=f["train"], heldout=f["test"], neighbour=f["neighbor"]) for f in facts],
                                                        real_world=retention))
    published = os.path.join(clone, "results", "exp9_eval")
    rows_checked = files = 0
    for name in sorted(os.listdir(published)):
        rows = read_json(os.path.join(published, name))["rows"]
        wrong = [r for r in rows if counts(r["answer"], r["target"]) != r["correct"]]
        if wrong:
            sys.exit(f"{name}: my match rule differs from their `correct` on {len(wrong)} rows, first {wrong[0]}")
        rows_checked, files = rows_checked + len(rows), files + 1
    print(f"the match rule gives their `correct` on all {rows_checked} published rows of {files} files")
    theirs = read_json(os.path.join(published, "base.json"))["rows"]
    mine = [(m, q, t) for m, _, q, t in jobs(read_json(os.path.join(out_dir, "eval.json")))]
    if mine != [(r["metric"], r["question"], r["target"]) for r in theirs]:
        sys.exit("the generated questions and targets are not those of their published rows")
    print(f"the generated evaluation equals their published rows: {len(mine)} questions and targets, in their order")


SETS = dict(efficacy="taught", generalization="heldout", bleed="neighbour", retention="real_world")


def jobs(ev: dict) -> list[tuple]:
    """(their metric, id, question, target) in the order of their evaluation: per fact its 3 editor questions, its 4 held-out ones and the
    neighbour's; then the real-world questions."""
    out = []
    for f in ev["facts"]:
        out += [("efficacy", f["id"], q, f["answer"]) for q in f["taught"]]
        out += [("generalization", f["id"], q, f["answer"]) for q in f["heldout"]]
        out.append(("bleed", f["id"], f["neighbour"], f["answer"]))
    return out + [("retention", r["id"], r["question"], r["answer"]) for r in ev["real_world"]]


def as_rows(job_list: list[tuple], replies: list[str]) -> list[dict]:
    """Rows without their question text: the set, the id, the position within that set and id, the target, the reply and the verdict."""
    seen, rows = {}, []
    for (metric, i, _, target), reply in zip(job_list, replies):
        k = seen.get((metric, i), 0)
        seen[(metric, i)] = k + 1
        rows.append(dict(set=SETS[metric], id=i, k=k, target=target, reply=reply, ok=counts(reply, target)))
    return rows


def write_rows(path: str, rows: list[dict]) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


def tally(rows: list[dict]) -> dict:
    out = {}
    for r in rows:
        a = out.setdefault(r["set"], [0, 0])
        a[0], a[1] = a[0] + r["ok"], a[1] + 1
    return {k: f"{v[0]} of {v[1]}" for k, v in out.items()}


# ---------------------------------------------------------------- wordings

def wordings(args):
    from cramschool.graft.wordings import Relation, check_kind, invented_companies, normalized

    out_dir, drafts = args[0], args[1:]
    editor, ev = read_json(os.path.join(out_dir, "editor.json")), read_json(os.path.join(out_dir, "eval.json"))
    drafted = {}
    for p in drafts:
        d = read_json(p)
        if set(d) & set(drafted):
            sys.exit(f"{p}: keys drafted twice: {sorted(set(d) & set(drafted))}")
        drafted.update(d)
    keys = [e["key"] for e in editor]
    if sorted(drafted) != sorted(keys + ["general"]):
        sys.exit(f"the drafts' keys are not the {len(keys)} relations and 'general': missing {sorted(set(keys + ['general']) - set(drafted))}, "
                 f"extra {sorted(set(drafted) - set(keys + ['general']))}")
    heldout = {normalized(slot(q)) for f in ev["facts"] for q in f["heldout"]}
    dropped, short, relations = [], [], {}

    def clean(items, taken, where):
        out = []
        for t in items:
            t = t.rstrip() if isinstance(t, str) else ""
            if t.count("{s}") != 1 or COMPANY.split()[0].lower() in t.lower():
                dropped.append((where, "no single {s} slot, or the company's name", t))
            elif normalized(t) in heldout:
                dropped.append((where, "equals a held-out question", "(not printed)"))
            elif normalized(t) in taken:
                dropped.append((where, "repeats a wording", t))
            else:
                taken.add(normalized(t))
                out.append(t)
        return out

    for e in editor:
        taught = [slot(q) for q in e["questions"]]
        taken = {normalized(t) for t in taught}
        plain = clean(drafted[e["key"]]["plain"], taken, e["key"] + " plain")
        chat = clean(drafted[e["key"]]["chat"], taken, e["key"] + " chat")
        if len(plain) < N_PLAIN or len(chat) < N_CHAT:
            short.append((e["key"], len(plain), len(chat)))
        relations[e["key"]] = Relation(name=e["key"], plain=plain, chat=taught + chat, person=e["kind"] == "leader", subject=KIND).as_dict()
    own = {normalized(t) for d in relations.values() for t in d["plain"] + d["chat"]}
    taken = set(own)
    general = dict(plain=clean(drafted["general"]["plain"], taken, "general plain"), chat=clean(drafted["general"]["chat"], taken, "general chat"))
    kind = check_kind(KIND, dict(names=invented_companies([COMPANY]), generic_plain=general["plain"], generic_chat=general["chat"]))
    write_json(os.path.join(out_dir, "wordings.json"), dict(relations=relations, kinds={KIND: kind}))
    by_reason = {}
    for _, reason, _ in dropped:
        by_reason[reason] = by_reason.get(reason, 0) + 1
    print(f"{len(relations)} relations of kind {KIND!r}: plain {sum(len(d['plain']) for d in relations.values())}, chat "
          f"{sum(len(d['chat']) for d in relations.values())} (3 taught questions first in each); general questions {len(kind['generic_plain'])} plain, "
          f"{len(kind['generic_chat'])} chat; invented names {len(kind['names'])}")
    print(f"dropped {len(dropped)}: {by_reason}")
    for where, reason, t in dropped:
        print(f"    {where}: {reason}: {t}")
    print(f"relations left with fewer than {N_PLAIN} plain or {N_CHAT} drafted chat wordings: {short if short else 'none'}")


# ---------------------------------------------------------------- the unedited model

def load(model_dir: str):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    tok = AutoTokenizer.from_pretrained(model_dir)
    model = AutoModelForCausalLM.from_pretrained(model_dir, dtype=torch.bfloat16, device_map="cuda").eval()
    return model, tok


def base(args):
    model_dir, out_dir, clone = args[:3]
    ev = read_json(os.path.join(out_dir, "eval.json"))
    job_list = jobs(ev)
    model, tok = load(model_dir)
    for name, context, theirs_name in (("base", None, "base"), ("base_context", "\n".join(f["statement"] for f in ev["facts"]), "base-context")):
        replies = answer(model, tok, [q for _, _, q, _ in job_list], context, name)
        rows = as_rows(job_list, replies)
        write_rows(os.path.join(out_dir, f"{name}.jsonl"), rows)
        theirs = read_json(os.path.join(clone, "results", "exp9_eval", f"{theirs_name}.json"))["rows"]
        same = sum(r["reply"] == t["answer"] for r, t in zip(rows, theirs))
        verdicts = sum(r["ok"] == t["correct"] for r, t in zip(rows, theirs))
        their_tally = tally([dict(set=SETS[t["metric"]], ok=t["correct"]) for t in theirs])
        print(f"{name}: mine {tally(rows)} | theirs {their_tally} | replies equal to theirs {same} of {len(rows)}, verdicts equal {verdicts}", flush=True)


# ---------------------------------------------------------------- build

def build(args):
    from cramschool import Graft
    from cramschool.graft.table import GraftOptions
    from cramschool.graft.wordings import Wordings
    from cramschool.model_access import render_chat

    model_dir, out_dir, table = args[:3]
    bare = "--bare" in args
    editor = read_json(os.path.join(out_dir, "editor.json"))
    model, tok = load(model_dir)
    probe = "What is {s} known for?".format(s=COMPANY)
    if not bare:
        want = protocol_prompt(tok, probe).text
        instruct(tok)
        if render_chat(tok, probe).text != want:
            sys.exit("the instructed tokenizer does not render the benchmark's chat format")
    print(f"chat wordings are taught {'as the package renders them (no system message)' if bare else 'in the benchmark chat format'}:\n"
          f"{render_chat(tok, probe).text!r}", flush=True)
    words = Wordings.builtin().with_file(os.path.join(out_dir, "wordings.json"))
    graft = Graft(model, tok, wordings=words, options=GraftOptions(fast=True, teach_cap=30, last_layer=None))  # step 23: the v1 write; ask --last-layer sets it
    t0 = time.time()
    for n, e in enumerate(editor, 1):
        stored = graft.add(COMPANY, e["key"], e["answer"])
        parts = graft._facts[-1]["parts"]
        print(f"[build {n}/{len(editor)}] {e['key']:38s} {stored.seconds:5.0f}s (total {time.time() - t0:.0f}s) counts {parts['counts']} "
              f"answer tokens { {sp: len(s['ids']) for sp, s in parts['spellings'].items() if s is not None} }", flush=True)
    graft.save(table)
    cache = graft._read_cache()
    print(f"{len(graft)} facts on {len({f.subject for f in graft.facts})} company; options {graft.options}; cache hits {cache.hits}, misses {cache.misses}; "
          f"built in {time.time() - t0:.0f}s; saved {table}", flush=True)


# ---------------------------------------------------------------- asking a table

def ask(args):
    from cramschool import Graft
    from cramschool.graft.wordings import Wordings, normalized

    model_dir, out_dir, table, out_path, which = args[:5]
    ev = read_json(os.path.join(out_dir, "eval.json"))
    if which not in ("taught", "all", "extras"):
        sys.exit("ask taught, all or extras")
    if which == "all" and os.path.exists(out_path):
        sys.exit(f"{out_path} exists: the held-out questions are asked once per table")
    model, tok = load(model_dir)
    graft = Graft.load(table, model, tok)
    if graft.options.prompt_detector or graft.options.looser_start or graft.options.arm or graft.options.end_quantile is not None:
        sys.exit("the table is not as built")
    if "--last-layer" in args:  # step 24: the same table with its answer tokens written at the last layer
        graft.options.last_layer = args[args.index("--last-layer") + 1]
    print(f"{table}: {len(graft)} facts, layer {graft.layer}, options {graft.options}", flush=True)
    if which == "extras":
        templates = {normalized(slot(q)) for f in ev["facts"] for q in f["taught"] + f["heldout"]}
        general = [t for t in Wordings.builtin().generic[1] if normalized(t) not in templates]
        job_list = [("general", f"g{n:02d}", t.format(s=COMPANY), "") for n, t in enumerate(general)]
        for name in OTHER_NAMES:
            job_list += [(f"name:{name}", f["id"], f["taught"][0].replace(COMPANY, name), f["answer"]) for f in ev["facts"]]
    else:
        job_list = [j for j in jobs(ev) if which == "all" or j[0] == "efficacy"]
    with graft.attached():
        replies = answer(model, tok, [q for _, _, q, _ in job_list], None, which)
        events = graft.events
    if which == "extras":
        answers = [f["answer"] for f in ev["facts"]]
        rows = [dict(set=m, id=i, target=t, reply=r, ok=counts(r, t) if t else False, stored=[a for a in answers if counts(r, a)],
                     **({"question": q} if m == "general" else {})) for (m, i, q, t), r in zip(job_list, replies)]  # the general questions are the package's own
    else:
        rows = as_rows(job_list, replies)
    write_rows(out_path, rows)
    print(f"{which}: {tally(rows)}; the layer's events {events}; written {out_path}", flush=True)


# ---------------------------------------------------------------- report

def report(args):
    from cramschool.bench.report import binom_two_sided

    out_dir, clone, judged_path = args[:3]
    shipped_path = args[3] if len(args) > 3 and not args[3].startswith("--") else None
    ev = read_json(os.path.join(out_dir, "eval.json"))
    kind = {f["id"]: f["kind"] for f in ev["facts"]}
    answers = {f["id"]: f["answer"] for f in ev["facts"]}
    kinds = list(dict.fromkeys(kind.values()))

    def theirs(name):
        rows = read_json(os.path.join(clone, "results", "exp9_eval", f"{name}.json"))["rows"]
        return as_rows([(r["metric"], r["id"], r["question"], r["target"]) for r in rows], [r["answer"] for r in rows])

    def summary(rows, base_rows):
        held = [r for r in rows if r["set"] == "heldout"]
        learned = sum(sum(r["ok"] for r in held if r["id"] == i) >= 3 for i in kind)
        base_ok = {r["id"] for r in base_rows if r["set"] == "real_world" and r["ok"]}
        kept = [r for r in rows if r["set"] == "real_world" and r["id"] in base_ok]
        return dict(taught=sum(r["ok"] for r in rows if r["set"] == "taught"), held=sum(r["ok"] for r in held), learned=learned,
                    kept=f"{sum(r['ok'] for r in kept)} of {len(kept)}", bleed=sum(r["ok"] for r in rows if r["set"] == "neighbour"),
                    by_kind={k: f"{sum(r['ok'] for r in held if kind[r['id']] == k)}/{sum(kind[r['id']] == k for r in held)}" for k in kinds})

    their_base, best = theirs("base"), theirs(THEIR_BEST)
    my_base = read_rows(os.path.join(out_dir, "base.jsonl"))
    table = [("their unedited model", summary(their_base, their_base)), ("their closed-form edit", summary(theirs("r1-L18-22"), their_base)),
             ("their editor-written circuit", summary(best, their_base))]
    judged = read_rows(judged_path)
    table.append(("GRAFT, taught in the benchmark's chat format (judged)", summary(judged, my_base)))
    shipped = read_rows(shipped_path) if shipped_path else None
    if shipped:
        table.append(("GRAFT as the package builds it (not judged)", summary(shipped, my_base)))
    print(f"{'':56s} taught/90  held-out/120  facts/30  real-world kept  bleed/30")
    for name, s in table:
        print(f"{name:56s} {s['taught']:6d} {s['held']:12d} {s['learned']:9d} {s['kept']:>16s} {s['bleed']:9d}")
